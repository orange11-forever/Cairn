// 01 基础标注与类型推断
//
// 标注的写法是「冒号 + 类型」，跟在变量名后面。
// 但真正要学的是：什么时候不该写。

// ─── 需要标注的情况：声明时还没有值 ───────────────────────

let count: number;
count = 0;

// ─── 不需要标注：有初始值时编译器自己能推断 ────────────────

let title = "未命名文档";
// 鼠标悬停（编辑器里）会显示 string。写成 let title: string = "..." 是噪音。

const 状态数 = 3;
// 注意 const 推断出的是字面量类型 3，不是 number。
// 因为 const 不能重新赋值，所以编译器可以断言得更死。

// ─── 三个基础类型 ─────────────────────────────────────────

const 文件名: string = "季度复盘.md";
const 页数: number = 12;
const 已就绪: boolean = true;

console.log(文件名, 页数, 已就绪, count, title, 状态数);

